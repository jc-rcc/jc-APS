const fs=require('fs'),vm=require('vm'),assert=require('assert/strict');
const auth=fs.readFileSync(__dirname+'/../public/js/auth.js','utf8');
const css=fs.readFileSync(__dirname+'/../public/css/responsive.css','utf8');
const printCss=fs.readFileSync(__dirname+'/../public/css/style.css','utf8');
assert.doesNotMatch(css,/@media\s*\(max-width/);
assert.match(css,/@media screen and \(max-width:768px\)/);
assert.match(css,/table:not\(\.ps-pay-table\) td/);
assert.match(printCss,/#printOverlay \.ps-pay-table tr\{display:table-row !important/);
assert.match(printCss,/#printOverlay \.ps-pay-table td::before\{display:none !important/);
const doc={innerHTML:'<article>Payslip</article>',querySelector:selector=>({textContent:selector.includes('ps-period')?'October 2026':'Paolo Mendoza'})};
let overlay,afterprint,printed=0;
const document={title:'RCC-APS',querySelector:()=>({id:'empPage'}),getElementById:id=>id==='psDoc'?doc:null,createElement:()=>({remove(){this.removed=true;}}),body:{appendChild:item=>{overlay=item;}}};
const window={addEventListener:(name,fn)=>{if(name==='afterprint')afterprint=fn;},removeEventListener:()=>{},print:()=>printed++};
const ctx=vm.createContext({document,window,showToast:()=>{throw new Error('unexpected toast');}});
vm.runInContext(auth.slice(auth.indexOf('function printPayslip()'),auth.indexOf('\nfunction showFinPage(')),ctx);
vm.runInContext('printPayslip()',ctx);
assert.equal(printed,1);
assert.equal(document.title,'Payslip_Paolo_Mendoza_October_2026');
assert.equal(overlay.removed,undefined);
assert.equal(overlay.innerHTML,doc.innerHTML);
afterprint();
assert.equal(overlay.removed,true);
assert.equal(document.title,'RCC-APS');
console.log('PASS: responsive styles exclude print/payslip tables; table display reset, correct filename, and cleanup waits for afterprint.');
